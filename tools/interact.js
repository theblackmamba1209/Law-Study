const { chromium } = require('/opt/npm-tools/node_modules/playwright');
(async () => {
  const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
  const pg = await b.newPage({ viewport: { width: 1280, height: 900 } });
  const errs = [];
  pg.on('pageerror', e => errs.push('PAGEERR ' + e.message));
  const base = 'http://localhost:8822/';
  await pg.goto(base + '#/p/rpc/article-3', { waitUntil: 'networkidle' });
  await pg.click('button[data-tab="recall"]'); await pg.waitForTimeout(300);
  await pg.click('[data-m="c2"]'); await pg.waitForTimeout(200);
  const blanks = await pg.$$eval('.cloze input', a => a.map(i => i.dataset.a));
  console.log('cloze blanks', blanks);
  await pg.click('#cc'); console.log(await pg.textContent('#cres'));
  await pg.click('[data-m="fr"]'); await pg.fill('#frt', 'Acts and omissions punishable by law are felonies (delitos).');
  await pg.click('#frc'); console.log((await pg.textContent('#frout')).slice(0, 160));
  await pg.click('button[data-rate="3"]'); await pg.waitForTimeout(800);
  console.log('after rate url', pg.url());
  const st = await pg.evaluate(() => JSON.parse(localStorage.getItem('sinag.codal.v1')).cards);
  console.log('cards', Object.keys(st).length, JSON.stringify(st['rpc|article-3']).slice(0, 120));
  await pg.goto(base + '#/drill?code=civil', { waitUntil: 'networkidle' });
  await pg.selectOption('#dscope', 'all'); await pg.selectOption('#dmode', 'cite'); await pg.click('#dgo'); await pg.waitForTimeout(1500);
  console.log('drill', (await pg.textContent('#drun')).slice(0, 200));
  await pg.click('[data-k="0"]'); console.log((await pg.textContent('#fb')).slice(0, 80));
  await pg.goto(base + '#/search?q=%22equitable%20mortgage%22', { waitUntil: 'networkidle' }); await pg.waitForTimeout(4000);
  console.log('search', (await pg.textContent('#sr')).slice(0, 200));
  await pg.goto(base + '#/p/const1987/art-iii-sec-3', { waitUntil: 'networkidle' });
  await pg.click('button[data-tab="cases"]'); await pg.waitForTimeout(300);
  console.log('cases', (await pg.textContent('#tabbox')).slice(0, 400));
  await pg.screenshot({ path: '/home/claude/work/shots/cases.png' });
  await pg.goto(base + '#/p/rpc/article-9', { waitUntil: 'networkidle' });
  console.log('amend', (await pg.textContent('#lawbox')).slice(0, 500));
  await pg.goto(base + 'legacy/', { waitUntil: 'load' }); await pg.waitForTimeout(1500);
  console.log('legacy', (await pg.textContent('body')).replace(/\s+/g, ' ').slice(0, 200));
  console.log(errs.join('\n') || 'NO PAGE ERRORS');
  await b.close();
})();
